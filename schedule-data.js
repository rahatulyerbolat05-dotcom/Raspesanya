function P(pair, name, teacher, room) {
  return { pair: pair, name: name, teacher: teacher, room: room || "413" };
}
function SPLIT(pair, numCls, denomCls) {
  // numCls / denomCls можно передать как null — значит в эту неделю пары просто нет.
  return {
    pair: pair,
    split: true,
    num:   numCls   ? { pair: pair, room: "413", name: numCls.name,   teacher: numCls.teacher,   room2: numCls.room }   : null,
    denom: denomCls ? { pair: pair, room: "413", name: denomCls.name, teacher: denomCls.teacher, room2: denomCls.room } : null
  };
}
